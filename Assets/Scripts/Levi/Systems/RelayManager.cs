using UnityEngine;
using Unity.Services.Core;
using Unity.Services.Authentication;
using Unity.Services.Relay;
using Unity.Services.Relay.Models;
using Unity.Netcode;
using Unity.Netcode.Transports.UTP;

public class RelayManager : MonoBehaviour
{
    public async void InitializeAndStartHost()
    {
        await UnityServices.InitializeAsync();
        if (!AuthenticationService.Instance.IsSignedIn)
        {
            await AuthenticationService.Instance.SignInAnonymouslyAsync();
        }

        // Create a Relay allocation for 1 client (max 2 players total)
        Allocation allocation = await RelayService.Instance.CreateAllocationAsync(1);

        // Retrieve the Join Code generated by Relay
        string joinCode = await RelayService.Instance.GetJoinCodeAsync(allocation.AllocationId);
        Debug.Log($"Relay Join Code: {joinCode}");

        // Configure Unity Transport using the built-in allocation extension method
        var transport = NetworkManager.Singleton.GetComponent<UnityTransport>();
        transport.SetRelayServerData(allocation.ToRelayServerData("dtls"));

        NetworkManager.Singleton.StartHost();
    }

    public async void JoinWithCode(string joinCode)
    {
        if (UnityServices.State == ServicesInitializationState.Uninitialized)
        {
            await UnityServices.InitializeAsync();
            if (!AuthenticationService.Instance.IsSignedIn)
            {
                await AuthenticationService.Instance.SignInAnonymouslyAsync();
            }
        }

        // Join the allocation using the entered join code
        JoinAllocation joinAllocation = await RelayService.Instance.JoinAllocationAsync(joinCode);

        // Configure Unity Transport for the joining client using the join allocation extension
        var transport = NetworkManager.Singleton.GetComponent<UnityTransport>();
        transport.SetRelayServerData(joinAllocation.ToRelayServerData("dtls"));

        NetworkManager.Singleton.StartClient();
    }
}